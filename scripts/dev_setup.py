"""Local development setup helpers (never used in production).

    python scripts/dev_setup.py env            create a git-ignored .env with fresh random secrets
    python scripts/dev_setup.py create-admin   set the admin password (typed twice, never stored)

Only the argon2 HASH of the password is written to the env file. The password itself is read
with ``getpass`` (no echo), is never put on a command line and is never logged.
"""

from __future__ import annotations

import argparse
import getpass
import os
import re
import secrets
import sys
import tempfile
from pathlib import Path

from argon2 import PasswordHasher

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_ENV = ROOT / ".env"
MIN_PASSWORD_CHARS = 12
HASH_KEY = "VIDGEN_ADMIN_PASSWORD_HASH"
# Matches docker-compose.yml, which uses these defaults for the local postgres container.
DB_URL = "postgresql+psycopg://vidgen:devpassword@127.0.0.1:5432/{name}"


def _write_private(path: Path, text: str) -> None:
    """Write ``text`` to ``path`` atomically with owner-only permissions."""
    handle, tmp_name = tempfile.mkstemp(dir=path.parent, prefix=".env.tmp.")
    try:
        with os.fdopen(handle, "w", encoding="utf-8") as tmp:
            tmp.write(text)
        os.chmod(tmp_name, 0o600)
        os.replace(tmp_name, path)
    except BaseException:
        Path(tmp_name).unlink(missing_ok=True)
        raise


def make_env_text(db_name: str) -> str:
    """The text of a fresh dev env file: random secrets, local services, no admin password yet."""
    lines = [
        "# Local development only. Generated by scripts/dev_setup.py. Git-ignored: never commit.",
        "VIDGEN_CREATOR_ENTITY='Local Dev'",
        f"VIDGEN_ENCRYPTION_KEY={secrets.token_hex(32)}",
        f"VIDGEN_INDEX_KEY={secrets.token_hex(32)}",
        f"VIDGEN_SESSION_SECRET={secrets.token_urlsafe(48)}",
        f"{HASH_KEY}=",
        f"VIDGEN_DATABASE_URL={DB_URL.format(name=db_name)}",
        "VIDGEN_REDIS_URL=redis://127.0.0.1:6379/0",
        "VIDGEN_STORAGE_ROOT=./media",
        "VIDGEN_AI_BACKEND=fake",
        "VIDGEN_COOKIE_SECURE=false",
        "",
    ]
    return "\n".join(lines)


def set_admin_hash(env_file: Path, password: str) -> None:
    """Store the argon2 hash of ``password`` in ``env_file`` (single-quoted: it contains ``$``)."""
    text = env_file.read_text(encoding="utf-8")
    entry = f"{HASH_KEY}='{PasswordHasher().hash(password)}'"
    pattern = re.compile(rf"^{HASH_KEY}=.*$", re.MULTILINE)
    new = pattern.sub(lambda _m: entry, text) if pattern.search(text) else text.rstrip("\n") + "\n" + entry + "\n"
    _write_private(env_file, new)


def cmd_env(args: argparse.Namespace) -> int:
    """Create the env file unless it already exists (an existing one is never overwritten)."""
    path = Path(args.env_file)
    if path.exists():
        print(f"{path.name} already exists: left untouched.")
        return 0
    _write_private(path, make_env_text(args.db_name))
    print(f"Created {path.name} with fresh random secrets (owner-only permissions).")
    return 0


def cmd_create_admin(args: argparse.Namespace) -> int:
    """Ask for the password twice and store only its hash."""
    path = Path(args.env_file)
    if not path.exists():
        print("No env file yet. Run scripts/dev_up.sh once first (it creates it).", file=sys.stderr)
        return 1
    first = getpass.getpass("New admin password (hidden): ")
    if len(first) < MIN_PASSWORD_CHARS:
        print(f"Use at least {MIN_PASSWORD_CHARS} characters.", file=sys.stderr)
        return 1
    if getpass.getpass("Type it again: ") != first:
        print("The two passwords differ. Nothing was changed.", file=sys.stderr)
        return 1
    set_admin_hash(path, first)
    print("Admin password set. Only its hash was saved.")
    return 0


def main() -> int:
    """Entry point."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--env-file", default=str(DEFAULT_ENV))
    sub = parser.add_subparsers(dest="command", required=True)
    env = sub.add_parser("env")
    env.add_argument("--db-name", default="vidgen")
    env.set_defaults(func=cmd_env)
    admin = sub.add_parser("create-admin")
    admin.set_defaults(func=cmd_create_admin)
    args = parser.parse_args()
    return int(args.func(args))


if __name__ == "__main__":
    raise SystemExit(main())
